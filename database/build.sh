#!/usr/bin/env bash
# Concatenates the ordered scripts into database/splitwise_plus.sql
# (single file to import in phpMyAdmin / mysql CLI). Run from repo root or database/.
set -euo pipefail
cd "$(dirname "$0")"
OUT=splitwise_plus.sql
{
  echo "-- SplitWise+ combined import file. GENERATED by database/build.sh — edit the source scripts instead."
  echo "-- Requires MySQL 8.0. Creates database splitwise_plus (drops it first)."
  for f in schema/01_create_database.sql schema/02_tables.sql schema/03_indexes.sql \
           functions/functions.sql views/views.sql triggers/triggers.sql \
           procedures/procedures.sql seeders/sample_data.sql; do
    echo; echo "-- >>> $f"; cat "$f"
  done
} > "$OUT"
echo "Wrote $OUT"
