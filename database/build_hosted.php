<?php
/**
 * Builds import scripts for a MANAGED MySQL 8.0 database (Phase 5.5).
 *
 *   DEMO_PASSWORD='…' APP_DB_PASSWORD='…' php database/build_hosted.php --db=splitwise_plus
 *
 * Output (folder build/, git-ignored — never commit it):
 *   build/hosted_schema.sql    tables, functions, views, triggers, procedures, sample data
 *                              - no DROP/CREATE DATABASE, no USE of a fixed name: imports into --db
 *                              - every sample user gets DEMO_PASSWORD instead of the public
 *                                Password@123 (a public URL must not have a published password)
 *   build/hosted_app_user.sql  least-privilege 'splitwise_app'@'%' with REQUIRE SSL
 * Passwords are read from environment variables only — never from the command line
 * (shell history) and never printed. If DEMO_PASSWORD is missing a random one is
 * generated and written to build/demo_password.txt (mode 600).
 * Import order: hosted_schema.sql as the provider's admin user, then hosted_app_user.sql.
 */
declare(strict_types=1);

$opts = getopt('', ['db:']);
$db = $opts['db'] ?? '';
if (!preg_match('/^[A-Za-z0-9_]{1,64}$/', $db)) {
    fwrite(STDERR, "Usage: DEMO_PASSWORD=… APP_DB_PASSWORD=… php database/build_hosted.php --db=NAME\n");
    exit(2);
}
$appPass = (string) getenv('APP_DB_PASSWORD');
if (strlen($appPass) < 16) {
    fwrite(STDERR, "Set APP_DB_PASSWORD (at least 16 characters) in the environment first.\n");
    exit(2);
}
$root = dirname(__DIR__);
$out = "$root/build";
if (!is_dir($out) && !mkdir($out, 0700, true)) {
    fwrite(STDERR, "Cannot create build/\n");
    exit(1);
}

// ---- schema + data
$sql = file_get_contents("$root/database/splitwise_plus.sql");
if ($sql === false) {
    fwrite(STDERR, "database/splitwise_plus.sql missing — run database/build.sh first\n");
    exit(1);
}
$sql = preg_replace('/^DROP DATABASE IF EXISTS splitwise_plus;\s*$/m', '', $sql);
$sql = preg_replace('/^CREATE DATABASE splitwise_plus.*?;\s*$/ms', '', $sql);
$sql = preg_replace('/^USE splitwise_plus;\s*$/m', '', $sql);
if (preg_match('/\bsplitwise_plus\b(?!\.sql)/', preg_replace('/^--.*$/m', '', $sql))) {
    fwrite(STDERR, "Unexpected hard-coded database name left in the script — aborting.\n");
    exit(1);
}
$demo = (string) getenv('DEMO_PASSWORD');
if ($demo === '') {
    $demo = rtrim(strtr(base64_encode(random_bytes(12)), '+/', 'Aa'), '=') . '@9';
    file_put_contents("$out/demo_password.txt", $demo . "\n");
    chmod("$out/demo_password.txt", 0600);
}
$hashes = [];
preg_match_all('/\$2y\$\d\d\$[.\/A-Za-z0-9]{53}/', $sql, $hashes);
$newHash = password_hash($demo, PASSWORD_BCRYPT);
$sql = str_replace(array_unique($hashes[0]), $newHash, $sql);
$head = "-- GENERATED by database/build_hosted.php for database `$db`. Do not commit.\n"
      . "-- Import as the provider's admin user (needs CREATE ROUTINE/TRIGGER; with binary logging\n"
      . "-- the server needs log_bin_trust_function_creators=1 or equivalent).\nSET NAMES utf8mb4;\nUSE `$db`;\n";
file_put_contents("$out/hosted_schema.sql", $head . $sql);

// ---- least-privilege app user, any host, TLS required
$q = fn(string $s): string => "'" . str_replace(["\\", "'"], ["\\\\", "\\'"], $s) . "'";
$u = "'splitwise_app'@'%'";
$owned = ['users', 'expense_groups', 'group_members', 'group_invitations', 'expenses', 'expense_splits', 'budgets',
          'notifications', 'receipts', 'tags', 'expense_tags', 'app_sessions', 'app_kv'];
$g = "-- GENERATED by database/build_hosted.php. Contains a password: do not commit, delete after use.\n"
   . "CREATE USER IF NOT EXISTS $u IDENTIFIED BY " . $q($appPass) . " REQUIRE SSL;\n"
   . "ALTER USER $u IDENTIFIED BY " . $q($appPass) . " REQUIRE SSL;\n"
   . "REVOKE ALL PRIVILEGES, GRANT OPTION FROM $u;\n"
   . "GRANT SELECT, EXECUTE ON `$db`.* TO $u;\n";
foreach ($owned as $t) {
    $g .= "GRANT INSERT, UPDATE, DELETE ON `$db`.`$t` TO $u;\n";
}
$g .= "-- settlements, audit_logs, categories: SELECT only\n";
file_put_contents("$out/hosted_app_user.sql", $g);
chmod("$out/hosted_app_user.sql", 0600);

echo "Wrote build/hosted_schema.sql and build/hosted_app_user.sql"
   . (getenv('DEMO_PASSWORD') === false || getenv('DEMO_PASSWORD') === '' ? " (demo password in build/demo_password.txt)" : '') . "\n";
