<?php
/**
 * One command that runs EVERY test suite — works on Windows (XAMPP) and Linux.
 * Needs: PHP with pdo_mysql + curl, the MySQL 8.0 "mysql" client, MySQL 8.0 server running.
 *
 *   php tests/run_all.php                              (root with no password, mysql on PATH)
 *   php tests/run_all.php --password=secret
 *   php tests/run_all.php --mysql="C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe" --password=secret
 *   php tests/run_all.php --build                      (also regenerate database/splitwise_plus.sql)
 *
 * Steps: unit -> import -> database suite + SQL scripts -> start app (as splitwise_app)
 *        -> functional suite -> money scenarios -> re-import clean sample data.
 * WARNING: drops and recreates the splitwise_plus database (sample data is restored at the end).
 */
declare(strict_types=1);

$opt = getopt('', ['mysql:', 'user:', 'password:', 'host:', 'port:', 'app-pass:', 'app-port:', 'build']);
$ROOT    = dirname(__DIR__);
$MYSQL   = $opt['mysql'] ?? 'mysql';
$USER    = $opt['user'] ?? 'root';
$PASS    = $opt['password'] ?? '';
$HOST    = $opt['host'] ?? '127.0.0.1';
$PORT    = $opt['port'] ?? '3306';
$APPPASS = $opt['app-pass'] ?? 'Change_Me_123!';   // must match database/security/app_user.sql
$APPPORT = $opt['app-port'] ?? '8765';
$PHP     = PHP_BINARY;
$results = [];
date_default_timezone_set(getenv('APP_TIMEZONE') ?: 'Asia/Kolkata');

// The root password goes into a temporary option file (mode 600), not onto the command
// line where other programs could read it and where mysql prints a warning each time.
$cnf = tempnam(sys_get_temp_dir(), 'swcnf');
file_put_contents($cnf, "[client]\npassword=\"" . addcslashes($PASS, "\\\"") . "\"\n");
@chmod($cnf, 0600);
$server = null;
register_shutdown_function(function () use (&$server, $cnf) {
    // 2. never leave the test web server running, even after a crash
    if (is_resource($server)) {
        proc_terminate($server);
    }
    @unlink($cnf);
});

function step(string $title): void { echo "\n=== $title\n"; }

/** Run a command (array form, no shell), stream output, return [exitCode, output]. */
function run(array $cmd, ?string $stdinFile = null, array $env = []): array
{
    $spec = [0 => $stdinFile ? ['file', $stdinFile, 'r'] : ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
    $p = proc_open($cmd, $spec, $pipes, null, $env ? array_merge(getenv(), $env) : null);
    if (!is_resource($p)) {
        return [127, 'could not start: ' . $cmd[0]];
    }
    if (!$stdinFile) { fclose($pipes[0]); }
    $out = stream_get_contents($pipes[1]) . stream_get_contents($pipes[2]);
    fclose($pipes[1]); fclose($pipes[2]);
    return [proc_close($p), $out];
}

$mysqlArgs = fn(): array => [$MYSQL, "--defaults-extra-file=$cnf", '--default-character-set=utf8mb4', '-h', $HOST, '-P', $PORT, '-u', $USER];
$sql = function (string $file) use ($mysqlArgs): array { return run($mysqlArgs(), $file); };
$import = function () use ($sql, $ROOT): bool {
    [$c, $o] = $sql("$ROOT/database/splitwise_plus.sql");
    if ($c !== 0) { echo $o; return false; }
    [$c, $o] = $sql("$ROOT/database/security/app_user.sql");
    if ($c !== 0) { echo $o; return false; }
    return true;
};
$mustImport = function () use ($import): void {
    if (!$import()) {
        echo "Re-import failed — stopping so no test runs on stale data.\n";
        exit(1);
    }
};
$cleanStorage = function () use ($ROOT): void {
    @unlink("$ROOT/storage/logs/mail.log");   // everything else (sessions, throttle, mail cursor, receipts) is in MySQL
};
$suite = function (string $name, array $cmd, array $env = []) use (&$results): void {
    [$code, $out] = run($cmd, null, $env);
    echo $out;
    preg_match('/(\d+) \/ (\d+) passed/', $out, $m);
    $results[] = [$name, $m ? "$m[1] / $m[2]" : 'no summary', $code === 0 ? 'PASS' : 'FAIL'];
};

// ---------------------------------------------------------------- 0. combined SQL file up to date?
$parts = ['schema/01_create_database.sql', 'schema/02_tables.sql', 'schema/03_indexes.sql', 'schema/04_infrastructure.sql', 'functions/functions.sql',
          'views/views.sql', 'triggers/triggers.sql', 'procedures/procedures.sql', 'seeders/sample_data.sql'];
$combined = "-- SplitWise+ combined import file. GENERATED by database/build.sh — edit the source scripts instead.\n"
          . "-- Requires MySQL 8.0. Creates database splitwise_plus (drops it first).\n";
foreach ($parts as $p) { $combined .= "\n-- >>> $p\n" . file_get_contents("$ROOT/database/$p"); }
if (isset($opt['build'])) {
    file_put_contents("$ROOT/database/splitwise_plus.sql", $combined);
    echo "Rebuilt database/splitwise_plus.sql\n";
} elseif (str_replace("\r\n", "\n", (string) file_get_contents("$ROOT/database/splitwise_plus.sql")) !== str_replace("\r\n", "\n", $combined)) {
    echo "WARNING: database/splitwise_plus.sql is out of date with the source scripts. Re-run with --build.\n";
}

// ---------------------------------------------------------------- 1. unit
step('Unit tests (no database)');
$suite('Unit (money, splits, simplifier)', [$PHP, "$ROOT/tests/unit/run_unit_tests.php"]);

// ---------------------------------------------------------------- 2. import
step('Import database + app account');
[$c, $o] = run(array_merge($mysqlArgs(), ['-N', '-e', 'SELECT VERSION()']));
echo 'Server: ' . trim($o) . "\n";
if ($c !== 0) { echo "Cannot run the mysql client. Use --mysql=\"path\\to\\mysql.exe\" and --password=...\n"; exit(1); }
if (!str_starts_with(trim($o), '8.0') || stripos($o, 'mariadb') !== false) { echo "WARNING: SplitWise+ targets MySQL 8.0; this server is " . trim($o) . "\n"; }
if (!$import()) { echo "Import failed.\n"; exit(1); }

// ---------------------------------------------------------------- 3. database
step('Database: install check + every SQL script');
$sqlOk = 0; $sqlFiles = array_merge(['database/verify_install.sql'], array_map(fn($f) => 'database/queries/' . basename($f), glob("$ROOT/database/queries/*.sql")),
    ['database/views/demo_views.sql', 'database/triggers/demo_triggers.sql', 'database/transactions/demo_acid.sql']);
foreach ($sqlFiles as $f) {
    [$c, $o] = $sql("$ROOT/$f");
    $ok = $c === 0 && !($f === 'database/verify_install.sql' && str_contains($o, 'FAIL'));
    echo ($ok ? 'OK   ' : 'FAIL ') . $f . ($ok ? '' : "\n$o") . "\n";
    $sqlOk += $ok ? 1 : 0;
}
$results[] = ['SQL scripts (queries, demos, install check)', "$sqlOk / " . count($sqlFiles), $sqlOk === count($sqlFiles) ? 'PASS' : 'FAIL'];
$dbEnv = ['DB_HOST' => $HOST, 'DB_PORT' => $PORT, 'DB_USER' => $USER, 'DB_PASS' => $PASS, 'APP_DB_PASS' => $APPPASS];
$suite('Database (schema, triggers, procedures, privileges)', [$PHP, "$ROOT/tests/database/run_db_tests.php"], $dbEnv);

// ---------------------------------------------------------------- 4. app server
step('Start the app on PHP\'s built-in server as splitwise_app');
$mustImport(); $cleanStorage();
$appEnv = array_merge(getenv(), ['DB_HOST' => $HOST, 'DB_PORT' => $PORT, 'DB_USER' => 'splitwise_app', 'DB_PASSWORD' => $APPPASS,
    'DB_NAME' => 'splitwise_plus', 'APP_DEBUG' => 'false']);
$log = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'splitwise-server.log';
$server = proc_open([$PHP, '-d', 'upload_max_filesize=6M', '-d', 'post_max_size=8M', '-S', "127.0.0.1:$APPPORT",
    '-t', "$ROOT/public", "$ROOT/public/router.php"], [0 => ['pipe', 'r'], 1 => ['file', $log, 'w'], 2 => ['file', $log, 'a']], $pipes, null, $appEnv);
$up = false;
for ($i = 0; $i < 40 && !$up; $i++) {          // up to ~10 seconds
    usleep(250_000);
    $st = proc_get_status($server);
    if (!$st['running']) {
        break;                                   // e.g. port already in use
    }
    $ctx = stream_context_create(['http' => ['timeout' => 2, 'ignore_errors' => true]]);
    $up = @file_get_contents("http://127.0.0.1:$APPPORT/login", false, $ctx) !== false;
}
if (!$up) {
    echo "The app did not start on port $APPPORT. Is the port in use? Try --app-port=8899.\nServer log:\n"
        . @file_get_contents($log) . "\n";
    exit(1);
}
echo "App is up on http://127.0.0.1:$APPPORT\n";
$httpEnv = ['APP_URL' => "http://127.0.0.1:$APPPORT", 'DB_HOST' => $HOST, 'DB_PORT' => $PORT, 'DB_ROOT_TCP' => '1',
    'DB_ROOT_USER' => $USER, 'DB_ROOT_PASS' => $PASS, 'APP_DB_PASS' => $APPPASS];

step('Functional tests (whole app over HTTP)');
$suite('Functional (HTTP end-to-end)', [$PHP, "$ROOT/tests/functional/run_functional_tests.php"], $httpEnv);

step('Money scenarios');
$mustImport(); $cleanStorage();
$suite('Money scenarios', [$PHP, "$ROOT/tests/functional/run_scenarios.php"], $httpEnv);

// ---------------------------------------------------------------- 5. clean up
proc_terminate($server);
$server = null;
$mustImport(); $cleanStorage();
echo "\nRe-imported clean sample data.\n";

step('Summary');
$all = true;
foreach ($results as [$name, $count, $status]) {
    printf("%-55s %-10s %s\n", $name, $count, $status);
    $all = $all && $status === 'PASS';
}
echo $all ? "\nALL SUITES PASSED\n" : "\nSOME SUITES FAILED — see output above\n";
exit($all ? 0 : 1);
